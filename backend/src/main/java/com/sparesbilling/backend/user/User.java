package com.sparesbilling.backend.user;

import jakarta.persistence.*;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

import java.time.LocalDateTime;

@Entity  //identifies a class as a database entity.
@Table(name = "users") //specifies the database table.
@Getter //identifies the primary key.
@Setter //configures how the primary key is generated.
@NoArgsConstructor  //This lets Lombok generate a constructor that takes no arguments.
public class User {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY) //specifies that the primary key is generated by the database.
    private Long id;

    @Column(nullable = false, unique = true, length = 50)  //@Column — configures a database column.
    private String username;

    @Column(name = "password_hash", nullable = false)
    private String passwordHash;

    @Column(name = "full_name", nullable = false, length = 100)
    private String fullName;

    @Enumerated(EnumType.STRING)  //@Enumerated - configures how an enum value is stored.
    @Column(nullable = false, length = 20)
    private Role role;

    @Column(nullable = false)
    private boolean active = true;

    @Column(name = "created_at", nullable = false, updatable = false)
    private LocalDateTime createdAt = LocalDateTime.now();
}